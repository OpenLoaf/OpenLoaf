/**
 * Static OOXML part templates used by the DOCX engine.
 *
 * Only stores *constant* XML fragments (no text substitution). The main
 * body (`word/document.xml`) and any parts that depend on content
 * (media rels, comment entries, etc.) are assembled by `docxEngine.ts`.
 *
 * Phase 0 populates this with the 5 legacy templates (migrated from the
 * original `wordTools.ts`) plus placeholders for the 4 comment parts
 * that Phase 4 will write when a document grows its first comment.
 */


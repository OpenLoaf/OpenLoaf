// ---------------------------------------------------------------------------
// Comment parts (Phase 4 — WordMutate.comment action)
// ---------------------------------------------------------------------------
//
// A DOCX with comments ships 4 extra parts:
//   word/comments.xml           — body text of each comment
//   word/commentsExtended.xml   — durable ids, done/parent metadata
//   word/commentsIds.xml        — paraId ↔ durable id mapping (Word 2013+)
//   word/people.xml             — author display list
//
// These empty-shell templates are emitted when the first comment is added
// and then appended to incrementally by docxReviewEngine helpers.

